    private fun normalize(value:String?)=if(value?.startsWith("es")==true)"es-MX" else "en"
    fun current(context:Context):String {
        if(Build.VERSION.SDK_INT>=33){val locales=context.getSystemService(LocaleManager::class.java).applicationLocales;if(!locales.isEmpty)return normalize(locales[0].toLanguageTag())}
        return normalize(context.getSharedPreferences("darwin",Context.MODE_PRIVATE).getString("appLanguage","en"))
    }
    fun wrap(context:Context):Context {
        val language=current(context);val config=Configuration(context.resources.configuration)
        config.setLocales(LocaleList.forLanguageTags(language));config.setLayoutDirection(Locale.forLanguageTag(language))
        return context.createConfigurationContext(config)
    }
    @Synchronized fun initialize(context:Context){tag=current(context);strings=wrap(context).resources;cache.clear()}
    fun choose(activity:Activity,language:String){
        val chosen=normalize(language);if(current(activity)==chosen)return
        activity.getSharedPreferences("darwin",Context.MODE_PRIVATE).edit().putString("appLanguage",chosen).commit()
        if(Build.VERSION.SDK_INT>=33)activity.getSystemService(LocaleManager::class.java).applicationLocales=LocaleList.forLanguageTags(chosen)
        initialize(activity);CastService.refreshLanguage()
        if(Build.VERSION.SDK_INT<33)activity.recreate()
    }
    @Synchronized fun text(english:String):String {
        if(tag=="en"||english.isEmpty())return english
        cache[english]?.let{return it}
        val resources=strings?:return english
        val exact=ids[english]?.let{resources.getString(it)}
        val translated=exact?:patterns.firstNotNullOfOrNull{(pattern,id)->pattern.matchEntire(english)?.let{m->resources.getString(id,*m.groupValues.drop(1).toTypedArray())}}?:english
        cache[english]=translated;return translated
    }
